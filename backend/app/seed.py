async def seed_questions() -> None:
    """向 questions 表批量插入面试题（幂等）"""
    async with AsyncSessionLocal() as session:
        # 检查是否已有数据
        result = await session.execute(select(func.count()).select_from(Question))
        existing_count = result.scalar() or 0
        if existing_count > 0:
            logger.info(f"题库已有 {existing_count} 道题目，跳过播种。如需重新播种请先清空 questions 表。")
            return

        objects = []
        for category, exam_type, province, content, difficulty, answer_ref in QUESTIONS_DATA:
            objects.append(
                Question(
                    category=category,
                    exam_type=exam_type,
                    province=province,
                    content=content,
                    difficulty=difficulty,
                    answer_reference=answer_ref,
                )
            )

        session.add_all(objects)
        await session.commit()
        logger.info(f"成功插入 {len(objects)} 道面试题。")


async def main() -> None:
    """种子脚本入口"""
    logger.info("开始执行数据库播种...")
    try:
        await seed_questions()
    finally:
        await async_engine.dispose()
    logger.info("播种完成。")


if __name__ == "__main__":
    asyncio.run(main())
